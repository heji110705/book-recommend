# 转折词：转折后情感权重更高（简单处理：遇到转折词，前半段得分折半）
TRANSITION_WORDS = {"但是", "不过", "然而", "可是", "但", "却", "虽然", "尽管", "可惜"}

# 情感词缓存（避免每次都重新构造集合）
_jieba_loaded = False


def _ensure_jieba():
    """向 jieba 加入自定义情感词，保证整词切分"""
    global _jieba_loaded
    if _jieba_loaded:
        return
    import logging

    jieba.setLogLevel(logging.WARNING)  # 关闭分词器加载日志
    for w in POSITIVE_WORDS | NEGATIVE_WORDS | NEGATION_WORDS | set(DEGREE_WORDS) | TRANSITION_WORDS:
        jieba.add_word(w)
    _jieba_loaded = True


def split_sentences(text: str) -> List[str]:
    """按中英文标点切分句子/分句"""
    parts = re.split(r"[。！？!?；;…\n]+", text)
    return [p.strip() for p in parts if p.strip()]


def analyze_comment(text: str) -> Dict:
    """
    分析单条评论情感。

    返回：
    {
        "score": float,          # 归一化情感分 [-1, 1]
        "polarity": str,         # pos / neu / neg
        "positive": float,       # 正向累计强度
        "negative": float,       # 负向累计强度
        "pos_words": [...],      # 命中正向词
        "neg_words": [...],      # 命中负向词
    }
    """
    _ensure_jieba()
    if not text:
        return {"score": 0.0, "polarity": "neu", "positive": 0.0, "negative": 0.0,
                "pos_words": [], "neg_words": []}

    pos_total = 0.0
    neg_total = 0.0
    pos_hit, neg_hit = [], []

    # 按分句处理，转折词只在分句内影响
    for sentence in split_sentences(text):
        tokens = jieba.lcut(sentence)
        # 处理转折：转折词之前的内容权重折半
        transition_idx = len(tokens)
        for i, t in enumerate(tokens):
            if t in TRANSITION_WORDS:
                transition_idx = i
                break

        for i, word in enumerate(tokens):
            sentiment_val = 0.0
            if word in POSITIVE_WORDS:
                sentiment_val = 1.0
                if word not in pos_hit:
                    pos_hit.append(word)
            elif word in NEGATIVE_WORDS:
                sentiment_val = -1.0
                if word not in neg_hit:
                    neg_hit.append(word)
            else:
                continue

            # 在前向窗口（前4个词）寻找否定词与程度副词
            window = tokens[max(0, i - 4):i]
            neg_count = sum(1 for w in window if w in NEGATION_WORDS)
            degree = 1.0
            for w in window:
                if w in DEGREE_WORDS:
                    degree = DEGREE_WORDS[w]
            # 否定：奇数次翻转，且强度衰减为 0.7
            if neg_count % 2 == 1:
                sentiment_val = -sentiment_val * 0.7
            sentiment_val *= degree
            # 转折前的内容权重折半
            if i < transition_idx and transition_idx < len(tokens):
                sentiment_val *= 0.5

            if sentiment_val > 0:
                pos_total += sentiment_val
            else:
                neg_total += abs(sentiment_val)

    denom = pos_total + neg_total
    score = 0.0 if denom == 0 else (pos_total - neg_total) / denom

    if score > 0.15:
        polarity = "pos"
    elif score < -0.15:
        polarity = "neg"
    else:
        polarity = "neu"

    return {
        "score": round(float(score), 4),
        "polarity": polarity,
        "positive": round(pos_total, 4),
        "negative": round(neg_total, 4),
        "pos_words": pos_hit,
        "neg_words": neg_hit,
        "keywords": "，".join((pos_hit + neg_hit)[:8]),
    }


def polarity_label(polarity: str) -> str:
    return {"pos": "好评", "neu": "中评", "neg": "差评"}.get(polarity, "中评")
